enum RoutePreset: Equatable, Hashable {
    case subscription
    case bypassPrivate
    case custom(count: Int)

    static func detect(in patch: OverridePatch) -> RoutePreset {
        guard let routes: [String] = patch.tunGet("route-address") else { return .subscription }
        return routes == bypassPrivateRouteAddress ? .bypassPrivate : .custom(count: routes.count)
    }

     
     
    func apply(to patch: inout OverridePatch) {
        switch self {
        case .subscription:
            patch.tunSet("route-address", nil as [String]?)
        case .bypassPrivate:
            patch.tunSet("route-address", Self.bypassPrivateRouteAddress)
        case .custom:
            break
        }
    }

     
     
     
     
